export type ImageKey = keyof typeof IMAGES;

export function hasImage(key: string): key is ImageKey {
  return Object.prototype.hasOwnProperty.call(IMAGES, key);
}

/** Converte um emoji no nome de arquivo do Twemoji (codepoints em hex, sem FE0F). */
export function twemojiFile(emoji: string): string {
  return [...emoji]
    .map((c) => c.codePointAt(0)!.toString(16))
    .filter((cp) => cp !== 'fe0f')
    .join('-');
}
